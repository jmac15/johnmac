/* ====================== jmac blog index page ================== */
/*
	Renders the post list and category sidebar on blog.html from
	window.BLOG_POSTS (see assets/js/blog-index.js, which is
	generated by build-blog-index.py — do not hand-edit that file).
*/
(function () {
	"use strict";

	function formatDate(iso) {
		var parts = (iso || "").split("-");
		if (parts.length !== 3) return iso || "";

		var d = new Date(Date.UTC(+parts[0], +parts[1] - 1, +parts[2]));

		return d.toLocaleDateString("en-GB", {
			day: "numeric",
			month: "long",
			year: "numeric",
			timeZone: "UTC"
		});
	}

	function init() {
		var $list = document.getElementById("blog-list");
		var $filters = document.getElementById("blog-filters");
		var $empty = document.getElementById("blog-empty");

		if (!$list || !$filters || !$empty) return;

		var posts = Array.isArray(window.BLOG_POSTS) ? window.BLOG_POSTS.slice() : [];

		if (posts.length === 0) {
			$empty.style.display = "";
			return;
		}

		// Count posts per tag, and collect the unique set alphabetically.
			var tagCounts = {};
			posts.forEach(function (post) {
				(post.tags || []).forEach(function (tag) {
					tagCounts[tag] = (tagCounts[tag] || 0) + 1;
				});
			});
			var tags = Object.keys(tagCounts).sort(function (a, b) {
				return a.localeCompare(b);
			});

		// Sidebar filter list: "All" plus one entry per category, each with a post count.
			var allLi = document.createElement("li");
			var allLink = document.createElement("a");
			allLink.href = "#";
			allLink.className = "active";
			allLink.setAttribute("data-tag", "");
			allLink.appendChild(document.createTextNode("All"));
			var allCount = document.createElement("span");
			allCount.className = "tag-count";
			allCount.textContent = "(" + posts.length + ")";
			allLink.appendChild(allCount);
			allLi.appendChild(allLink);
			$filters.appendChild(allLi);

			tags.forEach(function (tag) {
				var li = document.createElement("li");
				var a = document.createElement("a");
				a.href = "#";
				a.setAttribute("data-tag", tag);
				a.appendChild(document.createTextNode(tag));
				var count = document.createElement("span");
				count.className = "tag-count";
				count.textContent = "(" + tagCounts[tag] + ")";
				a.appendChild(count);
				li.appendChild(a);
				$filters.appendChild(li);
			});

		// Post list, most recent first (blog-index.js is already sorted this way).
			posts.forEach(function (post) {
				var li = document.createElement("li");
				li.className = "blog-item";
				li.setAttribute("data-tags", "|" + (post.tags || []).join("|") + "|");

				var dateEl = document.createElement("span");
				dateEl.className = "blog-item-date";
				dateEl.textContent = formatDate(post.date);

				var titleEl = document.createElement("a");
				titleEl.className = "blog-item-title";
				titleEl.href = post.file;
				titleEl.textContent = post.title;

				li.appendChild(dateEl);
				li.appendChild(titleEl);

				if (post.tags && post.tags.length) {
					var tagsEl = document.createElement("span");
					tagsEl.className = "blog-item-tags";
					post.tags.forEach(function (tag) {
						var pill = document.createElement("span");
						pill.className = "blog-tag-pill";
						pill.textContent = tag;
						tagsEl.appendChild(pill);
					});
					li.appendChild(tagsEl);
				}

				$list.appendChild(li);
			});

		// Filtering — a post can carry several tags, so it can show under any of them.
			$filters.addEventListener("click", function (event) {
				var target = event.target;
				while (target && target !== $filters && !target.hasAttribute("data-tag")) {
					target = target.parentNode;
				}
				if (!target || !target.hasAttribute("data-tag")) return;

				event.preventDefault();

				var tag = target.getAttribute("data-tag");

				var links = $filters.querySelectorAll("a");
				for (var i = 0; i < links.length; i++) {
					links[i].classList.toggle("active", links[i] === target);
				}

				var items = $list.querySelectorAll(".blog-item");
				var visibleCount = 0;
				for (var j = 0; j < items.length; j++) {
					var itemTags = items[j].getAttribute("data-tags") || "||";
					var show = !tag || itemTags.indexOf("|" + tag + "|") !== -1;
					items[j].style.display = show ? "" : "none";
					if (show) visibleCount++;
				}

				$empty.style.display = visibleCount ? "none" : "";
				$empty.textContent = tag ? 'No posts tagged "' + tag + '".' : "No posts yet — check back soon.";
			});
	}

	if (document.readyState === "loading") {
		document.addEventListener("DOMContentLoaded", init);
	} else {
		init();
	}
})();
