/* ====================== jmac photography page ================== */
/*
	Picks a random selection of photos from window.SITE_PHOTOS (see
	assets/js/photo-index.js, generated by build-photo-index.py — do
	not hand-edit that file) and renders them into the masonry grid
	on photography.html. Each thumbnail is wired up as a lightbox
	trigger (see the lightbox code in assets/js/main.js).
*/
(function () {
	"use strict";

	var PHOTO_COUNT = 20;

	function shuffle(array) {
		for (var i = array.length - 1; i > 0; i--) {
			var j = Math.floor(Math.random() * (i + 1));
			var temp = array[i];
			array[i] = array[j];
			array[j] = temp;
		}
		return array;
	}

	function init() {
		var grid = document.getElementById("photo-grid");
		var empty = document.getElementById("photo-empty");
		if (!grid) return;

		var all = Array.isArray(window.SITE_PHOTOS) ? window.SITE_PHOTOS.slice() : [];

		if (all.length === 0) {
			if (empty) empty.style.display = "";
			return;
		}

		var picked = shuffle(all).slice(0, Math.min(PHOTO_COUNT, all.length));

		picked.forEach(function (photo) {
			var figure = document.createElement("figure");
			figure.className = "photo-item";

			var link = document.createElement("a");
			link.href = photo.file;
			link.className = "lightbox-trigger";
			link.setAttribute("data-lightbox-group", "photography");
			link.setAttribute("data-caption", photo.alt);

			var img = document.createElement("img");
			img.src = photo.file;
			img.alt = photo.alt;
			img.loading = "lazy";

			link.appendChild(img);
			figure.appendChild(link);
			grid.appendChild(figure);
		});
	}

	if (document.readyState === "loading") {
		document.addEventListener("DOMContentLoaded", init);
	} else {
		init();
	}
})();
